import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

// Menghasilkan korpus retrieval untuk Tutor AI dari sumber kebenaran
// content/lessons. Hanya pelajaran validated/published yang disalin, dan
// tidak ada teks yang dikarang di sini: semua kalimat berasal dari berkas
// pelajaran yang sudah lolos gate penerbitan.
const scriptDir = import.meta.dirname;
const lessonsDir = join(scriptDir, '..', '..', 'content', 'lessons');
const outputPath = join(scriptDir, '..', 'src', 'tutor-corpus.js');

const lessons = readdirSync(lessonsDir)
  .filter((file) => file.endsWith('.json'))
  .map((file) => JSON.parse(readFileSync(join(lessonsDir, file), 'utf8')))
  .filter((lesson) => lesson.status === 'validated' || lesson.status === 'published')
  .sort((left, right) => left.id.localeCompare(right.id));

const chunks = [];
const dawanTerms = new Set();
const dawanPhrases = new Set();

function addDawan(value) {
  if (typeof value !== 'string') {
    return;
  }

  const phrase = value.toLowerCase().replaceAll('’', "'").replaceAll('ʔ', "'").trim();
  if (phrase.length > 0) {
    dawanPhrases.add(phrase);
  }

  for (const token of value.toLowerCase().match(/[\p{L}\p{M}']+/gu) ?? []) {
    if (token.length > 1) {
      dawanTerms.add(token);
    }
  }
}

function addChunk(lesson, kind, suffix, text, fields = {}) {
  chunks.push({
    id: `${lesson.id}#${suffix}`,
    lessonId: lesson.id,
    lessonTitle: lesson.title,
    topicId: lesson.topicId,
    kind,
    sourceRef: lesson.validation?.sources?.[0]?.id ?? null,
    text,
    ...fields
  });
}

for (const lesson of lessons) {
  addChunk(
    lesson,
    'lesson',
    'ringkasan',
    `Pelajaran "${lesson.title}". Ringkasan: ${lesson.summary} ` +
      `Tujuan: ${(lesson.objectives ?? []).join(' ')}`
  );

  for (const item of lesson.vocabulary ?? []) {
    addDawan(item.dawan);
    addChunk(
      lesson,
      'vocabulary',
      item.id,
      `Kosakata "${item.dawan}" berarti "${item.indonesian}". ` +
        (item.notes ? `Catatan: ${item.notes}` : ''),
      { dawan: item.dawan, indonesian: item.indonesian }
    );
  }

  for (const dialogue of lesson.dialogues ?? []) {
    for (const [index, line] of (dialogue.lines ?? []).entries()) {
      addDawan(line.dawan);
      addChunk(
        lesson,
        'dialogue',
        `${dialogue.id}-${index + 1}`,
        `Dialog "${dialogue.title}", penutur ${line.speaker}: ` +
          `"${line.dawan}" berarti "${line.indonesian}".`,
        { dawan: line.dawan, indonesian: line.indonesian }
      );
    }
  }

  for (const example of lesson.examples ?? []) {
    addDawan(example.dawan);
    addChunk(
      lesson,
      'example',
      example.id,
      `Contoh kalimat "${example.dawan}" berarti "${example.indonesian}". ` +
        (example.context ? `Konteks: ${example.context}` : ''),
      { dawan: example.dawan, indonesian: example.indonesian }
    );
  }

  for (const exercise of lesson.exercises ?? []) {
    const options = (exercise.content?.options ?? [])
      .map((option) => option.text)
      .join(', ');
    addChunk(
      lesson,
      'exercise',
      exercise.id,
      `Latihan: ${exercise.prompt} Pilihan: ${options}. ` +
        `Penjelasan: ${exercise.explanation}`
    );
  }
}

const corpus = {
  generatedFrom: 'content/lessons/*.json',
  lessons: lessons.map((lesson) => ({
    id: lesson.id,
    title: lesson.title,
    topicId: lesson.topicId,
    sourceRef: lesson.validation?.sources?.[0]?.id ?? null
  })),
  chunks,
  dawanTerms: [...dawanTerms].sort(),
  dawanPhrases: [...dawanPhrases].sort()
};

const output =
  '// Generated by scripts/generate-tutor-corpus.mjs. Do not edit.\n' +
  '// Sumber: content/lessons/*.json (hanya validated/published).\n' +
  'export const tutorCorpus = ' +
  JSON.stringify(corpus, null, 2) +
  ';\n';

writeFileSync(outputPath, output, 'utf8');
console.log(
  `Wrote ${chunks.length} chunks, ${corpus.dawanTerms.length} Dawan terms, ` +
    `and ${corpus.dawanPhrases.length} phrases from ${lessons.length} ` +
    `validated lessons to ${outputPath}`
);
