import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

// Menghasilkan daftar versi konten dari sumber kebenaran content/lessons.
// Hanya ID, versi, XP, dan status yang disalin; tidak ada teks Dawan.
const scriptDir = import.meta.dirname;
const lessonsDir = join(scriptDir, '..', '..', 'content', 'lessons');
const outputPath = join(scriptDir, '..', 'src', 'content-seed.js');

const entries = readdirSync(lessonsDir)
  .filter((file) => file.endsWith('.json'))
  .map((file) => {
    const lesson = JSON.parse(readFileSync(join(lessonsDir, file), 'utf8'));
    return {
      lessonId: lesson.id,
      contentVersion: lesson.schemaVersion,
      xp: lesson.xp,
      status: lesson.status
    };
  })
  .sort((left, right) => left.lessonId.localeCompare(right.lessonId));

const output =
  '// Generated by scripts/generate-content-seed.mjs. Do not edit.\n' +
  '// Sumber: content/lessons/*.json (hanya ID, versi, XP, status).\n' +
  'export const contentSeed = ' +
  JSON.stringify(entries, null, 2) +
  ';\n';

writeFileSync(outputPath, output, 'utf8');
console.log(`Wrote ${entries.length} content versions to ${outputPath}`);
